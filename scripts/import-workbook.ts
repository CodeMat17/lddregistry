/**
 * Repeatable workbook → seed normaliser.
 *
 *   yarn seed                               # uses data/source/DATABASE UPDATE-1.xlsx
 *   yarn seed path/to/other-workbook.xlsx
 *
 * Writes data/seed/*.json and docs/DATA_QUALITY_REPORT.md. Never merges,
 * deletes or corrects records; anomalies are flagged and reported.
 */
import { readFileSync, writeFileSync, mkdirSync, statSync } from "node:fs"
import { basename, resolve } from "node:path"
import { normaliseWorkbook } from "../lib/data/import/normalise"
import { readWorkbook } from "../lib/data/import/workbook"
import { findPossibleDuplicates } from "../lib/data/quality/duplicates"
import { FLAG_META } from "../lib/data/quality/flags"
import { SCHEMA_VERSION } from "../lib/data/schema"
import { CATEGORIES } from "../lib/domain/categories"
import type { DatasetMeta, DataQualityFlag } from "../lib/domain/types"

const input = resolve(process.argv[2] ?? "data/source/DATABASE UPDATE-1.xlsx")
const sourceFile = basename(input)
const generatedAt = statSync(input).mtime.toISOString()

const sheets = readWorkbook(readFileSync(input))
const { records, report } = normaliseWorkbook(sheets, { sourceFile, now: generatedAt, origin: "seed" })
const duplicates = findPossibleDuplicates(records)

const meta: DatasetMeta = {
  schemaVersion: SCHEMA_VERSION,
  datasetVersion: `${sourceFile}@${generatedAt}`,
  sourceFile,
  generatedAt,
  recordCount: records.length,
}

mkdirSync("data/seed", { recursive: true })
mkdirSync("docs", { recursive: true })
writeFileSync("data/seed/establishments.json", JSON.stringify(records))
writeFileSync("data/seed/meta.json", JSON.stringify(meta, null, 2))
writeFileSync(
  "data/seed/categories.json",
  JSON.stringify(
    CATEGORIES.map((c) => ({ ...c, recordCount: records.filter((r) => r.categoryId === c.id).length })),
    null,
    2,
  ),
)
writeFileSync("data/seed/import-report.json", JSON.stringify({ ...report, duplicates }, null, 2))

const md: string[] = []
md.push("# Data Quality Report", "")
md.push(`Generated by \`yarn seed\` from **${sourceFile}** (file modified ${generatedAt}).`, "")
md.push("This report is produced automatically by `scripts/import-workbook.ts`. The data is imported from the supplied workbook and has **not** been verified by NFVCB; it requires departmental validation. No record has been merged, deleted or corrected.", "")
md.push("## Worksheets", "", "| Worksheet | Register | Header row | Records | Blank rows skipped | Notes |", "|---|---|---|---|---|---|")
for (const s of report.sheets) {
  const notes = [...s.errors, ...s.warnings].join(" ").replace(/\|/g, "\\|") || "—"
  md.push(`| ${s.sheetName} | ${s.categoryId ?? "—"} | ${s.headerRow ?? "—"} | ${s.recordCount} | ${s.blankRowsSkipped} | ${notes} |`)
}
md.push("", `**Total records imported:** ${records.length}`, "")
md.push("## Flags", "", "| Flag | Severity | Records | Meaning |", "|---|---|---|---|")
for (const [flag, count] of Object.entries(report.flagCounts).sort((a, b) => b[1]! - a[1]!)) {
  const m = FLAG_META[flag as DataQualityFlag]
  md.push(`| ${m.label} | ${m.severity} | ${count} | ${m.description.replace(/\|/g, "\\|")} |`)
}
const where = (sheet: string, row: number) => `${sheet} r${row}`
md.push("", "## Unparseable or implausible dates", "", "| Location | Field | Raw value |", "|---|---|---|")
for (const d of report.dateIssues) md.push(`| ${where(d.sheet, d.row)} | ${d.field} | \`${d.raw}\` |`)
md.push("", "## Seating values excluded from totals", "", "| Location | Status | Raw value |", "|---|---|---|")
for (const s of report.seatIssues) md.push(`| ${where(s.sheet, s.row)} | ${s.status} | \`${s.raw}\` |`)
md.push("", "## Screen-count values excluded from totals", "", "| Location | Field | Raw value |", "|---|---|---|")
for (const s of report.screenIssues) md.push(`| ${where(s.sheet, s.row)} | ${s.field} | \`${s.raw}\` |`)
md.push("", "## Possible duplicates / related records", "", "Grouped by matching normalised name, phone or email. These may be legitimate separate registrations (for example the same operator in two registers). Only a user may confirm a relationship.", "")
md.push("| Match | Records |", "|---|---|")
const byId = new Map(records.map((r) => [r.id, r]))
for (const g of duplicates) {
  const list = g.recordIds.map((id) => { const r = byId.get(id)!; return `${r.name} (${where(r.sourceSheet, r.sourceRow)})` }).join("; ")
  const match = g.reasons.map((reason, i) => `${reason}: ${g.matchedOn[i] ?? ""}`).join("; ")
  md.push(`| ${match.replace(/\|/g, "\\|")} | ${list.replace(/\|/g, "\\|")} |`)
}
md.push("")
writeFileSync("docs/DATA_QUALITY_REPORT.md", md.join("\n"))

console.log(`Imported ${records.length} records from ${report.sheets.length} sheets → data/seed/`)
for (const s of report.sheets) console.log(`  ${s.sheetName.padEnd(24)} ${String(s.recordCount).padStart(4)} records (header row ${s.headerRow})`)
console.log(`Possible duplicate groups: ${duplicates.length}`)
